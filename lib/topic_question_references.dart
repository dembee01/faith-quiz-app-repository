List<QuizQuestion> withTopicQuestionReferences(
  String topic,
  List<QuizQuestion> questions,
) {
  final references = topicQuestionReferences[topic] ?? const <String>[];
  assert(
    references.length == questions.length,
    'Each topic question must have one Scripture reference.',
  );
  return List<QuizQuestion>.generate(questions.length, (index) {
    final question = questions[index];
    return QuizQuestion(
      question: question.question,
      options: question.options,
      correctAnswer: question.correctAnswer,
      explanation: question.explanation,
      verseReference: question.verseReference ?? references[index],
      verseText: question.verseText,
      translation: question.translation,
      commentary: question.commentary,
      crossRefs: question.crossRefs,
      learnMoreUrl: question.learnMoreUrl,
    );
  });
}
